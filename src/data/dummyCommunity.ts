export function findDummyCommunityUser(idOrName?: string): SearchedUserProfile | undefined {
  const clean = (idOrName || '').normalize('NFC').replace(/\s+/g, ' ').trim().toLowerCase();
  if (!clean) return undefined;
  return DUMMY_COMMUNITY_USERS.find(
    (u) =>
      u.id.toLowerCase() === clean ||
      u.displayName.normalize('NFC').toLowerCase() === clean ||
      (u.username || '').toLowerCase() === clean
  );
}
